// Utilidades de fecha, formato y cálculo. Sin dependencias.
export const pad = n => String(n).padStart(2, '0');
export const toStr = d => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
export const toDate = s => { const [y, m, d] = s.split('-').map(Number); return new Date(y, m - 1, d, 12); };
export const todayStr = () => toStr(new Date());
export const addDays = (s, n) => { const d = toDate(s); d.setDate(d.getDate() + n); return toStr(d); };
export const diffDays = (a, b) => Math.round((toDate(a) - toDate(b)) / 864e5);
export const nowTime = () => { const d = new Date(); return `${pad(d.getHours())}:${pad(d.getMinutes())}`; };
export const WEEKDAYS = ['domingo', 'lunes', 'martes', 'miércoles', 'jueves', 'viernes', 'sábado'];
export const WD_SHORT = ['D', 'L', 'M', 'X', 'J', 'V', 'S'];
export const MONTHS = ['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre'];
export const weekday = s => toDate(s).getDay();
export const fmtLong = s => { const d = toDate(s); return `${WEEKDAYS[d.getDay()]}, ${d.getDate()} de ${MONTHS[d.getMonth()]}`; };
export const fmtShort = s => { const d = toDate(s); return `${d.getDate()} ${MONTHS[d.getMonth()].slice(0, 3)}`; };
export const fmtFull = s => { const d = toDate(s); return `${d.getDate()} de ${MONTHS[d.getMonth()]} de ${d.getFullYear()}`; };
export const fmtMonth = s => { const d = toDate(s); return `${MONTHS[d.getMonth()]} ${d.getFullYear()}`; };
export const startOfWeek = s => addDays(s, -((weekday(s) + 6) % 7));
export const startOfMonth = s => s.slice(0, 8) + '01';
export const endOfMonth = s => { const d = toDate(s); return toStr(new Date(d.getFullYear(), d.getMonth() + 1, 0, 12)); };
export const dateRange = (a, b) => { const r = []; for (let c = a; c <= b; c = addDays(c, 1)) r.push(c); return r; };
export const uid = () => Date.now().toString(36) + Math.random().toString(36).slice(2, 8);
const ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
export const esc = s => s == null ? '' : String(s).replace(/[&<>"']/g, c => ESC[c]);
export const sum = a => a.reduce((x, y) => x + (Number(y) || 0), 0);
export const mean = a => { const v = a.filter(x => x != null && !Number.isNaN(x)); return v.length ? sum(v) / v.length : null; };
export const clamp = (x, a, b) => Math.min(b, Math.max(a, x));
export const round = (x, d = 0) => { if (x == null || Number.isNaN(x)) return null; const f = 10 ** d; return Math.round(x * f) / f; };
export const nf = (x, d = 0) => x == null || Number.isNaN(x) ? '—' : Number(x).toLocaleString('es-ES', { maximumFractionDigits: d, minimumFractionDigits: 0, useGrouping: 'always' });
export const pct = x => `${Math.round((x || 0) * 100)} %`;
export const numOrNull = v => { if (v === '' || v == null) return null; const n = Number(String(v).replace(',', '.')); return Number.isFinite(n) ? n : null; };
export const norm = s => (s || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
export const hours = h => { if (h == null) return '—'; const t = Math.round(h * 60); return `${Math.floor(t / 60)} h ${pad(t % 60)}`; };
